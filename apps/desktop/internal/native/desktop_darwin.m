static NSRunningApplication *gPrevFrontApp;
void sparkRememberFrontApp(void) {
	dispatch_async(dispatch_get_main_queue(), ^{
		NSRunningApplication *front = [[NSWorkspace sharedWorkspace] frontmostApplication];
		NSRunningApplication *selfApp = [NSRunningApplication currentApplication];
		if (front != nil && front.processIdentifier != selfApp.processIdentifier) {
			gPrevFrontApp = front;
		}
	});
}

void sparkRestoreFrontApp(void) {
	dispatch_async(dispatch_get_main_queue(), ^{
		if (gPrevFrontApp != nil && !gPrevFrontApp.terminated) {
			[gPrevFrontApp activateWithOptions:NSApplicationActivateIgnoringOtherApps];
		}
		gPrevFrontApp = nil;
	});
}

void sparkSetDockVisible(int visible) {
	dispatch_async(dispatch_get_main_queue(), ^{
		NSApplicationActivationPolicy policy = visible
			? NSApplicationActivationPolicyRegular
			: NSApplicationActivationPolicyAccessory;
		if ([NSApp activationPolicy] != policy) {
			[NSApp setActivationPolicy:policy];
		}
		if (visible) {
			[NSApp activateIgnoringOtherApps:YES];
		}
	});
}

// Inspect NSPasteboard while strictly filtering password manager concealed items.
int sparkReadClipboard(int *outChangeCount, int *outConcealed, char **outText, void **outPNG, size_t *outPNGLen) {
	*outChangeCount = 0;
	*outConcealed = 0;
	*outText = NULL;
	*outPNG = NULL;
	*outPNGLen = 0;

	@autoreleasepool {
		NSPasteboard *pb = [NSPasteboard generalPasteboard];
		*outChangeCount = (int)pb.changeCount;
		NSArray<NSPasteboardType> *types = pb.types;
		if (types == nil || types.count == 0) {
			return 0;
		}

		for (NSPasteboardType t in types) {
			if ([t isEqualToString:@"org.nspasteboard.ConcealedType"] ||
				[t isEqualToString:@"org.nspasteboard.AutoGeneratedType"] ||
				[t isEqualToString:@"org.nspasteboard.TransientType"] ||
				[t hasPrefix:@"com.agilebits.onepassword"]) {
				*outConcealed = 1;
				return 1;
			}
		}

		// Prefer PNG/TIFF image if present.
		NSData *pngData = [pb dataForType:NSPasteboardTypePNG];
		if (pngData == nil) {
			NSData *tiffData = [pb dataForType:NSPasteboardTypeTIFF];
			if (tiffData != nil) {
				NSBitmapImageRep *rep = [NSBitmapImageRep imageRepWithData:tiffData];
				if (rep != nil) {
					pngData = [rep representationUsingType:NSBitmapImageFileTypePNG properties:@{}];
				}
			}
		}
		if (pngData != nil && pngData.length > 0 && pngData.length <= 5 * 1024 * 1024) {
			void *buf = malloc((size_t)pngData.length);
			if (buf != NULL) {
				memcpy(buf, pngData.bytes, (size_t)pngData.length);
				*outPNG = buf;
				*outPNGLen = (size_t)pngData.length;
			}
			return 1;
		}

		NSString *str = [pb stringForType:NSPasteboardTypeString];
		if (str == nil) {
			str = [pb stringForType:NSPasteboardTypeURL];
		}
		if (str != nil && str.length > 0) {
			const char *utf8 = [str UTF8String];
			if (utf8 != NULL) {
				*outText = strdup(utf8);
			}
		}
		return 1;
	}
}

void sparkCopyText(const char *text) {
	if (text == NULL) return;
	NSString *str = [NSString stringWithUTF8String:text];
	if (str == nil) return;
	dispatch_async(dispatch_get_main_queue(), ^{
		NSPasteboard *pb = [NSPasteboard generalPasteboard];
		[pb clearContents];
		[pb setString:str forType:NSPasteboardTypeString];
	});
}

// Drag-and-drop overlay view attached onto our NSStatusItem button.
@interface SparkTrayDropView : NSView <NSDraggingDestination>
@property (nonatomic, strong) NSTimer *hoverTimer;
@end

static __weak SparkTrayDropView *trayOverlay;
static int trayIndicator;
void sparkTrayState(int state) {
    dispatch_async(dispatch_get_main_queue(), ^{
        trayIndicator = state;
        trayOverlay.needsDisplay = YES;
    });
}

@implementation SparkTrayDropView
- (instancetype)initWithFrame:(NSRect)frameRect {
	self = [super initWithFrame:frameRect];
	if (self) {
		self.autoresizingMask = NSViewWidthSizable | NSViewHeightSizable;
		[self registerForDraggedTypes:@[
			NSPasteboardTypeFileURL,
			NSPasteboardTypeURL,
			NSPasteboardTypeString,
			NSPasteboardTypePNG,
			NSPasteboardTypeTIFF
		]];
	}
	return self;
}

- (void)drawRect:(NSRect)rect {
    if (!trayIndicator) return;
    NSColor *color = trayIndicator == 2 ? NSColor.systemOrangeColor : NSColor.systemBlueColor;
    [color setFill];
    [[NSBezierPath bezierPathWithOvalInRect:NSMakeRect(NSMaxX(self.bounds)-7, 2, 5, 5)] fill];
}

- (NSView *)hitTest:(NSPoint)point {
	// Pass normal mouse clicks through to the underlying NSStatusBarButton.
	return nil;
}

- (NSDragOperation)draggingEntered:(id<NSDraggingInfo>)sender {
	[self.hoverTimer invalidate];
	self.hoverTimer = [NSTimer scheduledTimerWithTimeInterval:0.4 repeats:NO block:^(NSTimer * _Nonnull timer) {
		sparkGoTrayHoverExpand();
	}];
	return NSDragOperationCopy;
}

- (void)draggingExited:(id<NSDraggingInfo>)sender {
	[self.hoverTimer invalidate];
	self.hoverTimer = nil;
}

- (BOOL)performDragOperation:(id<NSDraggingInfo>)sender {
	[self.hoverTimer invalidate];
	self.hoverTimer = nil;

	NSPasteboard *pb = [sender draggingPasteboard];
	NSArray<NSURL *> *urls = [pb readObjectsForClasses:@[[NSURL class]] options:@{NSPasteboardURLReadingFileURLsOnlyKey: @YES}];
	if (urls != nil && urls.count > 0) {
		NSMutableArray<NSString *> *paths = [NSMutableArray array];
		for (NSURL *u in urls) {
			if (u.path.length > 0) [paths addObject:u.path];
		}
		if (paths.count > 0) {
			NSData *json = [NSJSONSerialization dataWithJSONObject:paths options:0 error:nil];
            NSString *joined = [[NSString alloc] initWithData:json encoding:NSUTF8StringEncoding];
			sparkGoTrayDropFiles((char *)[joined UTF8String]);
			return YES;
		}
	}
    NSData *png = [pb dataForType:NSPasteboardTypePNG];
    if (!png) {
        NSData *tiff = [pb dataForType:NSPasteboardTypeTIFF];
        if (tiff.length && tiff.length <= 5*1024*1024) {
            png = [[NSBitmapImageRep imageRepWithData:tiff] representationUsingType:NSBitmapImageFileTypePNG properties:@{}];
        }
    }
    if (png.length && png.length <= 5*1024*1024) {
        sparkGoTrayDropImage((void *)png.bytes,png.length);
        return YES;
    }
	NSString *text = [pb stringForType:NSPasteboardTypeURL];
	if (text == nil) text = [pb stringForType:NSPasteboardTypeString];
	if (text != nil && text.length > 0) {
		sparkGoTrayDropText((char *)[text UTF8String]);
		return YES;
	}
	return NO;
}
@end

static NSStatusBarButton *statusButtonInView(NSView *view) {
    if ([view isKindOfClass:NSStatusBarButton.class]) return (NSStatusBarButton *)view;
    for (NSView *child in view.subviews) {
        NSStatusBarButton *button = statusButtonInView(child);
        if (button) return button;
    }
    return nil;
}

void sparkAttachTrayDrop(void) {
    dispatch_async(dispatch_get_main_queue(), ^{
        for (NSWindow *window in NSApp.windows) {
            NSStatusBarButton *button = statusButtonInView(window.contentView);
            if (!button || trayOverlay) continue;
            SparkTrayDropView *view = [[SparkTrayDropView alloc] initWithFrame:button.bounds];
            [button addSubview:view];
            trayOverlay = view;
        }
    });
}

int sparkClipboardCount(void) { return (int)[NSPasteboard generalPasteboard].changeCount; }

void sparkPositionPanel(void *pointer) {
    if (!pointer) return;
    NSWindow *window = (__bridge NSWindow *)pointer;
    NSPoint mouse = NSEvent.mouseLocation;
    for (NSScreen *screen in NSScreen.screens) {
        if (!NSPointInRect(mouse, screen.frame)) continue;
        NSRect area = screen.visibleFrame;
        [window setFrameTopLeftPoint:NSMakePoint(NSMidX(area)-window.frame.size.width/2,NSMinY(area)+area.size.height*.78)];
        break;
    }
}

// Keep the menu-bar anchor stationary as the sheet grows downwards.
void sparkResizePanel(void *pointer, int height) {
    NSWindow *window = (__bridge NSWindow *)pointer;
    if (!window) return;
    NSRect frame = window.frame;
    frame.origin.y = NSMaxY(frame) - height;
    frame.size = NSMakeSize(460, height);
    if (NSEqualRects(frame, window.frame)) return;
    BOOL animate = window.isVisible && !NSWorkspace.sharedWorkspace.accessibilityDisplayShouldReduceMotion;
    [window setFrame:frame display:YES animate:animate];
}

